//! gm-store: SQLite persistence (rusqlite, bundled) + PGN import/export.
//!
//! * One `Mutex<Connection>` (WAL, foreign keys, busy timeout) shared by cheap `Store` clones.
//! * Schema migrations tracked with `PRAGMA user_version`; every migration is idempotent.
//! * All SQL is parameterized and goes through the (bounded) prepared-statement cache.
//! * User input is validated and size-capped; nothing on an input path panics.

