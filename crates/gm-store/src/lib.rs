    pub fn list_games(&self, q: &GameQuery) -> anyhow::Result<Vec<GameSummary>> {
        let mut sql = format!("SELECT {SUMMARY_COLS} FROM games WHERE 1=1");
        let mut args: Vec<Box<dyn ToSql>> = Vec::new();

        if let Some(search) = q
            .search
            .as_deref()
            .map(|s| clean_text(s, 100, false))
            .filter(|s| !s.is_empty())
        {
            let escaped = search
                .replace('\\', "\\\\")
                .replace('%', "\\%")
                .replace('_', "\\_");
            args.push(Box::new(format!("%{escaped}%")));
            let n = args.len();
            sql.push_str(&format!(
                " AND (white LIKE ?{n} ESCAPE '\\' OR black LIKE ?{n} ESCAPE '\\' \
                 OR opening_name LIKE ?{n} ESCAPE '\\' OR notes LIKE ?{n} ESCAPE '\\' \
                 OR tags LIKE ?{n} ESCAPE '\\' OR termination LIKE ?{n} ESCAPE '\\' \
                 OR bot_id LIKE ?{n} ESCAPE '\\')"
            ));
        }
        if let Some(result) = q
            .result
            .as_deref()
            .map(str::trim)
            .filter(|s| !s.is_empty() && *s != "all")
        {
            match result.to_ascii_lowercase().as_str() {
                "win" | "won" | "wins" => sql.push_str(
                    " AND ((user_color = 'white' AND result = '1-0') OR (user_color = 'black' AND result = '0-1'))",
                ),
                "loss" | "lost" | "losses" => sql.push_str(
                    " AND ((user_color = 'white' AND result = '0-1') OR (user_color = 'black' AND result = '1-0'))",
                ),
                "draw" | "draws" => sql.push_str(" AND result = '1/2-1/2'"),
                "unfinished" | "ongoing" => sql.push_str(" AND result = '*'"),
                _ => {
                    args.push(Box::new(pgn::normalize_result(result).to_string()));
                    sql.push_str(&format!(" AND result = ?{}", args.len()));
                }
            }
        }
        if let Some(bot) = q.bot_id.as_deref().map(str::trim).filter(|s| !s.is_empty()) {
            args.push(Box::new(bot.to_string()));
            sql.push_str(&format!(" AND bot_id = ?{}", args.len()));
        }
        if let Some(fav) = q.favorite {
            args.push(Box::new(fav as i64));
            sql.push_str(&format!(" AND favorite = ?{}", args.len()));
        }
        let limit = q.limit.unwrap_or(DEFAULT_LIMIT).clamp(1, MAX_LIMIT);
        let offset = q.offset.unwrap_or(0).min(10_000_000);
        args.push(Box::new(limit as i64));
        args.push(Box::new(offset as i64));
        sql.push_str(&format!(
            " ORDER BY created_at DESC, id DESC LIMIT ?{} OFFSET ?{}",
            args.len() - 1,
            args.len()
        ));

        let conn = self.conn.lock();
        let mut stmt = conn.prepare_cached(&sql)?;
        let refs: Vec<&dyn ToSql> = args.iter().map(|b| b.as_ref()).collect();
        let rows = stmt.query_map(refs.as_slice(), row_to_summary)?;
        Ok(rows.collect::<Result<Vec<_>, _>>()?)
    }

