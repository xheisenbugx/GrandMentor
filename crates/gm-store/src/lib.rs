type Migration = fn(&rusqlite::Transaction<'_>) -> rusqlite::Result<()>;

/// Index i migrates user_version i -> i+1. Append only; never edit a shipped migration.
const MIGRATIONS: &[Migration] = &[migrate_v1, migrate_v2, migrate_v3];

fn has_column(tx: &rusqlite::Transaction<'_>, table: &str, col: &str) -> rusqlite::Result<bool> {
    let mut stmt = tx.prepare("SELECT 1 FROM pragma_table_info(?1) WHERE name = ?2")?;
    stmt.exists(params![table, col])
}

fn migrate_v1(tx: &rusqlite::Transaction<'_>) -> rusqlite::Result<()> {
    tx.execute_batch(
        r#"
CREATE TABLE IF NOT EXISTS games (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  white TEXT NOT NULL DEFAULT '', black TEXT NOT NULL DEFAULT '',
  result TEXT NOT NULL DEFAULT '*', termination TEXT NOT NULL DEFAULT '',
  start_fen TEXT NOT NULL DEFAULT '', moves TEXT NOT NULL DEFAULT '', pgn TEXT NOT NULL DEFAULT '',
  bot_id TEXT, user_color TEXT, time_control TEXT, opening_name TEXT,
  accuracy_white REAL, accuracy_black REAL, review_json TEXT,
  notes TEXT NOT NULL DEFAULT '', tags TEXT NOT NULL DEFAULT '', favorite INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
CREATE TABLE IF NOT EXISTS profile (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  name TEXT NOT NULL DEFAULT 'Player',
  avatar TEXT NOT NULL DEFAULT '♟️',
  puzzle_rating REAL NOT NULL DEFAULT 1200,
  puzzle_rd REAL NOT NULL DEFAULT 350,
  rush_best INTEGER NOT NULL DEFAULT 0,
  puzzles_solved INTEGER NOT NULL DEFAULT 0,
  puzzles_failed INTEGER NOT NULL DEFAULT 0,
  streak_days INTEGER NOT NULL DEFAULT 0,
  last_active TEXT NOT NULL DEFAULT '',
  settings_json TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
INSERT OR IGNORE INTO profile (id) VALUES (1);
CREATE TABLE IF NOT EXISTS puzzle_attempts (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  puzzle_id TEXT NOT NULL,
  puzzle_rating INTEGER NOT NULL,
  solved INTEGER NOT NULL,
  time_ms INTEGER NOT NULL DEFAULT 0,
  rating_before REAL NOT NULL,
  rating_after REAL NOT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_puzzle_attempts_puzzle ON puzzle_attempts(puzzle_id);
CREATE TABLE IF NOT EXISTS rating_history (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kind TEXT NOT NULL DEFAULT 'puzzle',
  attempt_id INTEGER REFERENCES puzzle_attempts(id) ON DELETE CASCADE,
  rating REAL NOT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_rating_history_kind ON rating_history(kind, id);
CREATE TABLE IF NOT EXISTS rush_scores (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  score INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
CREATE TABLE IF NOT EXISTS lesson_progress (
  course_id TEXT NOT NULL,
  lesson_id TEXT NOT NULL,
  completed INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  PRIMARY KEY (course_id, lesson_id)
) WITHOUT ROWID;
"#,
    )?;
    // A pre-migration scaffold may have created `games` without these columns.
    if !has_column(tx, "games", "headers_json")? {
        tx.execute_batch("ALTER TABLE games ADD COLUMN headers_json TEXT NOT NULL DEFAULT '[]'")?;
    }
    if !has_column(tx, "games", "move_count")? {
        tx.execute_batch("ALTER TABLE games ADD COLUMN move_count INTEGER NOT NULL DEFAULT 0")?;
        tx.execute_batch(
            "UPDATE games SET move_count = CASE WHEN moves = '' THEN 0 \
             ELSE length(moves) - length(replace(moves, ' ', '')) + 1 END",
        )?;
    }
    tx.execute_batch(
        r#"
CREATE INDEX IF NOT EXISTS idx_games_created ON games(created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_games_bot ON games(bot_id);
CREATE INDEX IF NOT EXISTS idx_games_favorite ON games(favorite);
"#,
    )?;
    Ok(())
}

