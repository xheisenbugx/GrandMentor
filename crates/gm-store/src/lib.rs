    /// Rates a puzzle attempt (Glicko-2-lite) and returns the new rating and the change, both
    /// rounded to whole points as shown to the user.
    pub fn record_puzzle_attempt(
        &self,
        puzzle_id: &str,
        puzzle_rating: u16,
        solved: bool,
        time_ms: u64,
    ) -> anyhow::Result<PuzzleResult> {
        let puzzle_id = clean_text(puzzle_id, 64, false);
        if puzzle_id.is_empty() {
            bail!("puzzle id is required");
        }
        let time_ms = time_ms.min(24 * 3600 * 1000) as i64;
        let mut conn = self.conn.lock();
        let tx = conn.transaction()?;
        let (old_r, old_rd): (f64, f64) = tx
            .prepare_cached("SELECT puzzle_rating, puzzle_rd FROM profile WHERE id = 1")?
            .query_row([], |r| Ok((r.get(0)?, r.get(1)?)))?;
        let (new_r, new_rd) = rating::update(old_r, old_rd, f64::from(puzzle_rating), solved);
        tx.prepare_cached(
            "INSERT INTO puzzle_attempts (puzzle_id, puzzle_rating, solved, time_ms, rating_before, rating_after) \
             VALUES (?1, ?2, ?3, ?4, ?5, ?6)",
        )?
        .execute(params![puzzle_id, puzzle_rating, solved as i64, time_ms, old_r, new_r])?;
        let attempt_id = tx.last_insert_rowid();
        tx.prepare_cached(
            "INSERT INTO rating_history (kind, attempt_id, rating) VALUES ('puzzle', ?1, ?2)",
        )?
        .execute(params![attempt_id, new_r])?;
        tx.prepare_cached(
            "UPDATE profile SET puzzle_rating = ?1, puzzle_rd = ?2, \
             puzzles_solved = puzzles_solved + ?3, puzzles_failed = puzzles_failed + ?4 WHERE id = 1",
        )?
        .execute(params![new_r, new_rd, solved as i64, (!solved) as i64])?;
        touch_activity(&tx)?;
        prune(&tx, "rating_history")?;
        prune(&tx, "puzzle_attempts")?;
        tx.commit()?;
        let shown_new = new_r.round();
        Ok(PuzzleResult {
            rating: shown_new as f32,
            delta: (shown_new - old_r.round()) as f32,
        })
    }

    /// Records a Puzzle Rush score; returns the best score ever.
    pub fn record_rush(&self, score: u32) -> anyhow::Result<u32> {
        let score = score.min(10_000) as i64;
        let mut conn = self.conn.lock();
        let tx = conn.transaction()?;
        tx.prepare_cached("INSERT INTO rush_scores (score) VALUES (?1)")?
            .execute([score])?;
        tx.prepare_cached("UPDATE profile SET rush_best = MAX(rush_best, ?1) WHERE id = 1")?
            .execute([score])?;
        touch_activity(&tx)?;
        prune(&tx, "rush_scores")?;
        let best: i64 = tx
            .prepare_cached("SELECT rush_best FROM profile WHERE id = 1")?
            .query_row([], |r| r.get(0))?;
        tx.commit()?;
        Ok(to_u32(best))
    }

