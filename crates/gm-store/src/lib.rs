fn migrate(conn: &mut Connection) -> anyhow::Result<()> {
    let current: i64 = conn.query_row("PRAGMA user_version", [], |r| r.get(0))?;
    let target = MIGRATIONS.len() as i64;
    if current > target {
        bail!("database schema version {current} is newer than this build supports ({target})");
    }
    for (i, m) in MIGRATIONS.iter().enumerate().skip(current.max(0) as usize) {
        let tx = conn.transaction()?;
        m(&tx).with_context(|| format!("migration to schema v{}", i + 1))?;
        // PRAGMA cannot be parameterized; the value is a trusted integer.
        tx.execute_batch(&format!("PRAGMA user_version = {}", i + 1))?;
        tx.commit()?;
    }
    Ok(())
}

fn configure(conn: &Connection, wal: bool) -> anyhow::Result<()> {
    conn.busy_timeout(std::time::Duration::from_secs(5))?;
    if wal {
        let mode: String =
            conn.pragma_update_and_check(None, "journal_mode", "WAL", |r| r.get(0))?;
        if !mode.eq_ignore_ascii_case("wal") {
            tracing::warn!("SQLite WAL mode unavailable (journal_mode = {mode})");
        }
        conn.pragma_update(None, "synchronous", "NORMAL")?;
    }
    conn.pragma_update(None, "foreign_keys", "ON")?;
    conn.pragma_update(None, "temp_store", "MEMORY")?;
    // Bounded page cache (~8 MiB).
    conn.pragma_update(None, "cache_size", -8000)?;
    conn.set_prepared_statement_cache_capacity(STMT_CACHE);
    Ok(())
}

