/// Trim, drop control characters (except newlines/tabs when `multiline`) and cap length (chars).
fn clean_text(s: &str, max_chars: usize, multiline: bool) -> String {
    s.trim()
        .chars()
        .filter(|c| !c.is_control() || (multiline && (*c == '\n' || *c == '\t')))
        .take(max_chars)
        .collect::<String>()
        .trim_end()
        .to_string()
}

fn clean_opt(s: &Option<String>, max: usize) -> Option<String> {
    s.as_deref()
        .map(|v| clean_text(v, max, false))
        .filter(|v| !v.is_empty())
}

fn clean_tags(tags: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for t in tags {
        let t = clean_text(t, MAX_TAG_LEN, false);
        if !t.is_empty() && !out.iter().any(|o| o.eq_ignore_ascii_case(&t)) {
            out.push(t);
            if out.len() >= MAX_TAGS {
                break;
            }
        }
    }
    out
}

fn clean_color(c: &Option<String>) -> Option<String> {
    match c.as_deref().map(|s| s.trim().to_ascii_lowercase()) {
        Some(s) if s == "white" || s == "w" => Some("white".into()),
        Some(s) if s == "black" || s == "b" => Some("black".into()),
        _ => None,
    }
}

fn clean_accuracy(a: Option<f32>) -> Option<f32> {
    a.filter(|v| v.is_finite()).map(|v| v.clamp(0.0, 100.0))
}

/// Validates and canonicalizes a start FEN + UCI move list.
fn validate_game(start_fen: &str, moves: &[String]) -> anyhow::Result<(String, Vec<String>)> {
    if moves.len() > pgn::MAX_PLIES {
        bail!("too many moves (max {})", pgn::MAX_PLIES);
    }
    let fen = pgn::canonical_fen(start_fen).map_err(|e| anyhow!("invalid start position: {e}"))?;
    let moves: Vec<String> = moves
        .iter()
        .map(|m| m.trim().to_ascii_lowercase())
        .collect();
    pgn::uci_to_sans(&fen, &moves).map_err(|e| anyhow!("invalid move list: {e}"))?;
    Ok((fen, moves))
}

fn tags_to_db(tags: &[String]) -> String {
    serde_json::to_string(tags).unwrap_or_else(|_| "[]".into())
}

fn tags_from_db(s: &str) -> Vec<String> {
    let s = s.trim();
    if s.is_empty() {
        return Vec::new();
    }
    serde_json::from_str::<Vec<String>>(s).unwrap_or_else(|_| {
        s.split(',')
            .map(|t| t.trim().to_string())
            .filter(|t| !t.is_empty())
            .collect()
    })
}

fn moves_from_db(s: &str) -> Vec<String> {
    s.split_whitespace().map(str::to_string).collect()
}

fn headers_from_db(s: &str) -> Vec<(String, String)> {
    serde_json::from_str(s).unwrap_or_default()
}

fn set_header(headers: &mut Vec<(String, String)>, name: &str, value: Option<&str>) {
    let idx = headers
        .iter()
        .position(|(k, _)| k.eq_ignore_ascii_case(name));
    match (idx, value.filter(|v| !v.is_empty())) {
        (Some(i), Some(v)) => headers[i].1 = v.to_string(),
        (None, Some(v)) => headers.push((name.to_string(), v.to_string())),
        (Some(i), None) => {
            headers.remove(i);
        }
        (None, None) => {}
    }
}

/// "win" | "loss" | "draw" | "unfinished" from the user's perspective.
fn outcome_for(user_color: Option<&str>, result: &str) -> &'static str {
    match (user_color, result) {
        (_, "1/2-1/2") => "draw",
        (Some("white"), "1-0") | (Some("black"), "0-1") => "win",
        (Some("white"), "0-1") | (Some("black"), "1-0") => "loss",
        _ => "unfinished",
    }
}

fn round1(v: f64) -> f32 {
    ((v * 10.0).round() / 10.0) as f32
}

