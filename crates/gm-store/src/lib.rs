    pub fn create_game(&self, g: &NewGame) -> anyhow::Result<GameRecord> {
        let g = clean_new_game(g);
        let (fen, moves) = validate_game(&g.start_fen, &g.moves)?;
        let conn = self.conn.lock();
        let date: String = conn
            .prepare_cached("SELECT strftime('%Y.%m.%d','now','localtime')")?
            .query_row([], |r| r.get(0))?;
        let mut headers: Vec<(String, String)> = vec![
            (
                "Event".into(),
                if g.bot_id.is_some() {
                    "GrandMentor vs Bot".into()
                } else {
                    "GrandMentor Game".into()
                },
            ),
            ("Site".into(), "GrandMentor".into()),
            ("Date".into(), date),
            ("Round".into(), "-".into()),
            ("White".into(), g.white.clone()),
            ("Black".into(), g.black.clone()),
            ("Result".into(), g.result.clone()),
        ];
        set_header(&mut headers, "TimeControl", g.time_control.as_deref());
        set_header(&mut headers, "Termination", Some(g.termination.as_str()));
        set_header(&mut headers, "Opening", g.opening_name.as_deref());
        let id = insert_game(&conn, &g, &fen, &moves, &headers)?;
        if g.user_color.is_some() {
            touch_activity(&conn)?;
        }
        get_game_in(&conn, id)?.ok_or_else(|| anyhow!("game {id} vanished after insert"))
    }

    pub fn update_game(&self, id: i64, patch: &GamePatch) -> anyhow::Result<Option<GameRecord>> {
        // Validate the expensive / fallible bits before taking the lock.
        if let Some(r) = &patch.review_json {
            if r.len() > MAX_REVIEW_BYTES {
                bail!("review too large");
            }
            serde_json::from_str::<serde::de::IgnoredAny>(r)
                .map_err(|e| anyhow!("review_json is not valid JSON: {e}"))?;
        }

        let conn = self.conn.lock();
        let Some(mut g) = get_game_in(&conn, id)? else {
            return Ok(None);
        };
        let mut regenerate = false;

        if let Some(moves) = &patch.moves {
            let (_, moves) = validate_game(&g.start_fen, moves)?;
            if moves != g.moves {
                g.moves = moves;
                regenerate = true;
            }
        }
        if let Some(r) = &patch.result {
            let r = pgn::normalize_result(r).to_string();
            if r != g.result {
                g.result = r;
                regenerate = true;
            }
        }
        if let Some(t) = &patch.termination {
            let t = clean_text(t, MAX_TERMINATION, false);
            if t != g.termination {
                g.termination = t;
                regenerate = true;
            }
        }
        if let Some(n) = &patch.notes {
            g.notes = clean_text(n, MAX_NOTES, true);
        }
        if let Some(t) = &patch.tags {
            g.tags = clean_tags(t);
        }
        if let Some(f) = patch.favorite {
            g.favorite = f;
        }
        if let Some(r) = &patch.review_json {
            g.review_json = Some(r.clone());
        }
        if patch.accuracy_white.is_some() {
            g.accuracy_white = clean_accuracy(patch.accuracy_white);
        }
        if patch.accuracy_black.is_some() {
            g.accuracy_black = clean_accuracy(patch.accuracy_black);
        }

        let mut headers = get_headers_in(&conn, id)?;
        if regenerate {
            if headers.is_empty() {
                headers = vec![
                    ("White".into(), g.white.clone()),
                    ("Black".into(), g.black.clone()),
                ];
            }
            set_header(&mut headers, "Result", Some(&g.result));
            set_header(&mut headers, "Termination", Some(&g.termination));
            g.pgn = pgn::to_pgn(&headers, &g.start_fen, &g.moves, &g.result);
        }

        conn.prepare_cached(&format!(
            "UPDATE games SET result = ?2, termination = ?3, moves = ?4, pgn = ?5, \
             accuracy_white = ?6, accuracy_black = ?7, review_json = ?8, notes = ?9, tags = ?10, \
             favorite = ?11, headers_json = ?12, move_count = ?13, updated_at = {NOW} WHERE id = ?1"
        ))?
        .execute(params![
            id,
            g.result,
            g.termination,
            g.moves.join(" "),
            g.pgn,
            g.accuracy_white.map(f64::from),
            g.accuracy_black.map(f64::from),
            g.review_json,
            g.notes,
            tags_to_db(&g.tags),
            g.favorite as i64,
            serde_json::to_string(&headers).unwrap_or_else(|_| "[]".into()),
            g.moves.len() as i64,
        ])?;
        get_game_in(&conn, id)
    }

    pub fn delete_game(&self, id: i64) -> anyhow::Result<bool> {
        let conn = self.conn.lock();
        let n = conn
            .prepare_cached("DELETE FROM games WHERE id = ?1")?
            .execute([id])?;
        Ok(n > 0)
    }

    /// Imports every game of a (multi-game) PGN atomically. Games with illegal moves are
    /// skipped when others parse; if none parse, the parse error is returned.
    pub fn import_pgn(&self, text: &str) -> anyhow::Result<Vec<GameRecord>> {
        self.import_pgn_with(text, |_, _| None)
    }

    /// Like [`Store::import_pgn`], but `name_opening(start_fen, uci_moves)` supplies an opening
    /// name for games whose PGN has no `Opening` tag.
    pub fn import_pgn_with(
        &self,
        text: &str,
        name_opening: impl Fn(&str, &[String]) -> Option<String>,
    ) -> anyhow::Result<Vec<GameRecord>> {
        let games = pgn::parse_pgn(text).map_err(|e| anyhow!("could not read PGN: {e}"))?;
        if games.len() > MAX_IMPORT_GAMES {
            bail!("too many games in one import (max {MAX_IMPORT_GAMES})");
        }
        let mut conn = self.conn.lock();
        let tx = conn.transaction()?;
        let mut ids = Vec::with_capacity(games.len());
        for pg in &games {
            let h = |k: &str| {
                pg.header(k)
                    .map(str::to_string)
                    .filter(|v| !v.is_empty() && v != "?")
            };
            let opening = h("Opening")
                .map(|o| match h("Variation") {
                    Some(v) => format!("{o}: {v}"),
                    None => o,
                })
                .or_else(|| name_opening(&pg.start_fen, &pg.moves));
            let ng = clean_new_game(&NewGame {
                white: h("White").unwrap_or_default(),
                black: h("Black").unwrap_or_default(),
                result: pg.result.clone(),
                termination: h("Termination").unwrap_or_default(),
                start_fen: pg.start_fen.clone(),
                moves: pg.moves.clone(),
                bot_id: None,
                user_color: None,
                time_control: h("TimeControl").filter(|t| t != "-"),
                opening_name: opening,
                notes: String::new(),
                tags: vec!["imported".into()],
            });
            let mut headers: Vec<(String, String)> = pg
                .headers
                .iter()
                .filter(|(k, _)| !k.eq_ignore_ascii_case("SetUp") && !k.eq_ignore_ascii_case("FEN"))
                .cloned()
                .collect();
            set_header(&mut headers, "Result", Some(&ng.result));
            ids.push(insert_game(&tx, &ng, &pg.start_fen, &pg.moves, &headers)?);
        }
        tx.commit()?;
        let mut out = Vec::with_capacity(ids.len());
        for id in ids {
            if let Some(g) = get_game_in(&conn, id)? {
                out.push(g);
            }
        }
        Ok(out)
    }

    /// Concatenated PGN of all games matching `q` (for "export library").
    pub fn export_pgn(&self, q: &GameQuery) -> anyhow::Result<String> {
        let ids: Vec<i64> = self.list_games(q)?.into_iter().map(|g| g.id).collect();
        let conn = self.conn.lock();
        let mut out = String::new();
        let mut stmt = conn.prepare_cached("SELECT pgn FROM games WHERE id = ?1")?;
        for id in ids {
            if let Some(p) = stmt.query_row([id], |r| r.get::<_, String>(0)).optional()? {
                out.push_str(p.trim_end());
                out.push_str("\n\n");
            }
        }
        Ok(out)
    }

