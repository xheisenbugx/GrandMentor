    #[test]
    fn puzzle_rating_monotonic() {
        let s = Store::open_in_memory().unwrap();
        let p0 = s.get_profile().unwrap();
        assert_eq!(p0.puzzle_rating, 1200.0);
        assert_eq!(p0.puzzle_rd, 350.0);
        let mut last = p0.puzzle_rating;
        for i in 0..10 {
            let r = s
                .record_puzzle_attempt(&format!("p{i}"), 1300, true, 5000)
                .unwrap();
            assert!(r.delta >= 1.0 && r.rating > last, "{r:?}");
            assert_eq!(r.rating, last + r.delta);
            last = r.rating;
        }
        for i in 0..10 {
            let r = s
                .record_puzzle_attempt(&format!("q{i}"), 1300, false, 5000)
                .unwrap();
            assert!(r.delta <= -1.0 && r.rating < last, "{r:?}");
            last = r.rating;
        }
        let p = s.get_profile().unwrap();
        assert_eq!(p.puzzles_solved, 10);
        assert_eq!(p.puzzles_failed, 10);
        assert!(p.puzzle_rd < 350.0);
        assert_eq!(p.puzzle_rating, last);
        assert_eq!(p.streak_days, 1);
        let st = s.stats().unwrap();
        assert_eq!(st.rating_history.len(), 20);
        assert_eq!(st.rating_history.last().unwrap().rating, last);
        assert!(s.record_puzzle_attempt("", 1200, true, 0).is_err());
    }

